import { standardShortZh } from "@common/lib/mbtiStandardShortZh";

/** 将「您属于{标准中文}人格」改为「您属于 CODE · 标准中文人格」；不匹配则原样返回 */
function youBelongWithCode(userMbtiUpper: string, text: string): string {
  const zh = standardShortZh(userMbtiUpper);
  const needle = `您属于${zh}人格`;
  if (text.startsWith(needle)) {
    return `您属于${userMbtiUpper} · ${zh}人格` + text.slice(needle.length);
  }
  return text;
}

