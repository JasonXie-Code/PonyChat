export function getTypeProfile(code: string): TypeProfile | null {
  const key = code.toUpperCase();
  return typeProfiles[key] ?? null;
}

/** 标题/友伴行等与标准站统一用通用中文简称；长文案仍用本文件 typeProfiles.nickname */
export function shortTypeName(code: string): string {
  return standardShortZh(code);
}

export interface LetterExplainRow {
  pole: string;
  detail: string;
  dimLabel: string;
}

/** 根据四字母返回当前结果里每个维度对应的一句解释 */
export function explainLetters(code: string): LetterExplainRow[] {
  const u = code.toUpperCase();
  if (u.length !== 4) return [];
  const letters = u.split("");
  const axes: (keyof typeof poleDisplayName)[] = ["EI", "SN", "TF", "JP"];
  return letterHints.map((h, i) => {
    const ch = letters[i];
    const isLeft =
      i === 0
        ? ch === "E"
        : i === 1
          ? ch === "S"
          : i === 2
            ? ch === "T"
            : ch === "J";
    const [leftPole, rightPole] = poleDisplayName[axes[i]];
    const pole = isLeft ? leftPole : rightPole;
    const detail = isLeft ? h.left : h.right;
    return { pole, detail, dimLabel: h.label };
  });
}
