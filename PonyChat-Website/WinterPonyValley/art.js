  const ponySprites = new WeakMap();

  function drawPony(g, x, y, pony, time = 0, moving = false, facing = 1, portrait = false) {
    const step = moving ? Math.floor(time * 15) % steps.length : -1;
    const blink = !portrait && time % 4.7 > 4.53;
    const key = (step + 1) * 2 + Number(blink);
    let poses = ponySprites.get(pony);
    if (!poses) {
      poses = [];
      ponySprites.set(pony, poses);
    }
    if (!poses[key]) {
      const sprite = document.createElement('canvas');
      sprite.width = spriteSize;
      sprite.height = spriteSize;
      const p = sprite.getContext('2d');
      p.translate(spriteOriginX, spriteOriginY);
      paintPony(p, pony, step, blink);
      poses[key] = sprite;
    }

    g.save();
    g.translate(x, y);
    g.scale(facing, 1);
    if (!portrait) ellipse(g, '#58698562', -2, 0, 9, 3);
    g.imageSmoothingEnabled = true;
    const size = spriteSize * spriteScale;
    g.drawImage(poses[key], -spriteOriginX * spriteScale, -spriteOriginY * spriteScale, size, size);
    g.restore();
  }

