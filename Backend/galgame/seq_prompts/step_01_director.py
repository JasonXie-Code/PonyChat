def build_seq_step1_director_core_instruction(
    *,
    is_lock_mode: bool,
    key_order_line: str,
) -> str:
    """第 1 步导演提示的主干：第一节～第六节（规则与 JSON 说明），不含第七节本轮上下文。"""
    if is_lock_mode:
        sec1 = _SEQ1_SEC1_FOOTER_LOCK
        p51 = _SEQ1_P51_RESTRAINT_LOCK
        p52 = _SEQ1_P52_BODY_STATE_LOCK
        p53 = _SEQ1_P53_CORE_LOCK
        p55 = _SEQ1_P55_INNER_EXTRAS_LOCK
        p57 = _SEQ1_P57_EXTRAS_LOCK
        s5 = _SEQ1_S5_NARRATIVE_COMPLETION_LOCK
    else:
        sec1 = _SEQ1_SEC1_FOOTER_NORMAL
        p51 = _SEQ1_P51_RESTRAINT_NORMAL
        p52 = _SEQ1_P52_BODY_STATE_NORMAL
        p53 = _SEQ1_P53_CORE_NORMAL
        p55 = _SEQ1_P55_INNER_EXTRAS_NORMAL
        p57 = _SEQ1_P57_EXTRAS_NORMAL
        s5 = _SEQ1_S5_NARRATIVE_COMPLETION_NORMAL
    return _SEQ_STEP1_DIRECTOR_TEMPLATE.format(
        sec1_footer=sec1,
        p51_restraint=p51,
        p52_body_state_line=p52,
        p53_core_reaction=p53,
        p55_inner_extras=p55,
        p57_extras=p57,
        s5_narrative_completion=s5,
        key_order_line=key_order_line,
    )


def build_seq_step1_round_context_section(
    *,
    current_score: int,
    player_action: str,
    prev_state_block: str,
    player_info_line: str = "",
) -> str:
    """第七节：好感度、记忆与玩家行为；须在锁分附录（若有）之后拼接，作整条提示词末尾。"""
    _pi = (player_info_line or "").strip()
    _player_info_block = f"\n{_pi}\n" if _pi else ""
    return _SEQ_STEP1_ROUND_CONTEXT_TEMPLATE.format(
        current_score=current_score,
        player_action=player_action,
        prev_state_block=prev_state_block,
        player_info_block=_player_info_block,
    )


