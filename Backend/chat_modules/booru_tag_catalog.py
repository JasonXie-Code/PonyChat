def is_literal_booru_tag(tag: str, *, allow_exclusions: bool = True) -> bool:
    """Allow plain tags and verified colon-bearing names, never query operators."""
    prefix = "-?" if allow_exclusions else ""
    return bool(re.fullmatch(prefix + r"[a-z0-9][a-z0-9 '()_-]{0,79}", tag)
                and not re.search(r"\b(or|not|and)\b", tag)) or (
        (allow_exclusions or not tag.startswith("-")) and tag.removeprefix("-") in _COLON_TAGS
    )
